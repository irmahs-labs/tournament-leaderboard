-- The release 1 schema, from the migration plan: accounts, organisations and their members,
-- players, seasons with their own scoring rules, matches, games and stats.
-- Every tournament row belongs to one organisation, directly or through its season or match.

-- Accounts and organisations ---------------------------------------------------------------

CREATE TABLE app_users (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  google_sub         varchar NOT NULL UNIQUE,      -- Google's stable account id; emails can change
  email              varchar NOT NULL,
  display_name       varchar,
  avatar_url         varchar,
  is_platform_admin  boolean NOT NULL DEFAULT false,
  created_at         timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE organizations (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug               varchar NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$'),
  name               varchar NOT NULL,
  tournament_name    varchar,                      -- "Spike Tournament"
  description        varchar(200),                 -- one line for the home page card
  default_locale     varchar(2) NOT NULL DEFAULT 'en' CHECK (default_locale IN ('en', 'fr')),
  accent_color       varchar(7) CHECK (accent_color ~ '^#[0-9A-Fa-f]{6}$'),
  scan_enabled       boolean NOT NULL DEFAULT false,
  players_per_match  smallint NOT NULL DEFAULT 10 CHECK (players_per_match BETWEEN 2 AND 40),
  next_season_rules  jsonb,                        -- rules saved with "Next season only"
  last_activity_at   timestamptz,                  -- set when a game is saved or deleted
  status             varchar NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED')),
  created_by         uuid REFERENCES app_users(id) ON DELETE SET NULL,
  created_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX organizations_last_activity ON organizations (last_activity_at DESC) WHERE status = 'ACTIVE';

CREATE TABLE organization_logos (
  organization_id  uuid PRIMARY KEY REFERENCES organizations(id) ON DELETE CASCADE,
  content_type     varchar NOT NULL CHECK (content_type IN ('image/png', 'image/webp', 'image/svg+xml')),
  bytes            bytea NOT NULL,
  updated_at       timestamptz NOT NULL DEFAULT now()
);

-- Players ----------------------------------------------------------------------------------

-- Valorant ranks, shared by every organisation. The rows come with the Supabase import, so
-- their ids match the ones players already point to.
CREATE TABLE ranks (
  id          smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rank_name   varchar NOT NULL,
  rank_value  smallint,
  color       varchar(7) CHECK (color ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE players (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id   uuid NOT NULL REFERENCES organizations(id),
  riot_id           varchar NOT NULL,              -- current Riot ID, shown everywhere: Kestrel#EUW
  discord_username  varchar,
  current_rank_id   smallint REFERENCES ranks(id)
);
-- The same person at two organisations is two player rows.
CREATE UNIQUE INDEX players_org_riot_id ON players (organization_id, lower(riot_id));

CREATE TABLE player_aliases (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  player_id   uuid NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  alias       varchar NOT NULL,
  kind        varchar NOT NULL CHECK (kind IN ('PREVIOUS_RIOT_ID', 'NICKNAME', 'OTHER')),
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX player_aliases_player ON player_aliases (player_id);

-- Members and invites ----------------------------------------------------------------------

CREATE TABLE organization_members (
  user_id          uuid NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  organization_id  uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  role             varchar NOT NULL CHECK (role IN ('ADMIN', 'PLAYER')),
  is_owner         boolean NOT NULL DEFAULT false CHECK (NOT is_owner OR role = 'ADMIN'),
  player_id        uuid UNIQUE REFERENCES players(id),
  joined_at        timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, organization_id)
);
CREATE UNIQUE INDEX one_owner_per_organization
  ON organization_members (organization_id) WHERE is_owner;

CREATE TABLE organization_invites (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id  uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  kind             varchar NOT NULL CHECK (kind IN ('PERSONAL', 'SHARED')),
  email            varchar,                -- PERSONAL: the only Google email that can use it
  role             varchar NOT NULL CHECK (role IN ('ADMIN', 'PLAYER')),   -- PERSONAL: ADMIN; SHARED: PLAYER
  code_hash        bytea NOT NULL UNIQUE,
  invited_by       uuid REFERENCES app_users(id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  expires_at       timestamptz NOT NULL,   -- 30 min, 1 h, 12 h, 24 h or 48 h after creation
  max_uses         smallint,               -- SHARED: empty means no limit; PERSONAL: always 1
  use_count        smallint NOT NULL DEFAULT 0,
  revoked_at       timestamptz,
  CHECK ((kind = 'PERSONAL' AND role = 'ADMIN' AND email IS NOT NULL)
      OR (kind = 'SHARED' AND role = 'PLAYER' AND email IS NULL))
);

-- Seasons and their scoring rules ----------------------------------------------------------

CREATE TABLE seasons (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id  uuid NOT NULL REFERENCES organizations(id),
  number           smallint NOT NULL,                -- restarts at 1 in each organisation
  name             varchar NOT NULL,                 -- "Season 3"
  starts_on        date,
  ends_on          date,
  match_count      smallint NOT NULL CHECK (match_count BETWEEN 1 AND 20),
  min_games        smallint NOT NULL,
  max_games        smallint NOT NULL,                -- "2 to 5", "Fixed: 3", "Fixed: 5"
  points_per_win   smallint NOT NULL DEFAULT 50,
  finished_at      timestamptz,
  CHECK (1 <= min_games AND min_games <= max_games AND max_games <= 9),
  UNIQUE (organization_id, number)
);

CREATE TABLE season_stat_rules (
  season_id  integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
  stat       varchar NOT NULL CHECK (stat IN ('PERFORMANCE_SCORE', 'KILLS', 'DEATHS', 'ASSISTS',
                                     'ECON_RATING', 'FIRST_BLOODS', 'PLANTS', 'DEFUSES',
                                     'HEADSHOT_PCT', 'CLUTCHES')),
  recorded   boolean NOT NULL,                                 -- asked for in games entered from now on
  effect     smallint NOT NULL CHECK (effect IN (-1, 0, 1)),   -- subtracts, not counted, adds
  PRIMARY KEY (season_id, stat)
);

CREATE TABLE season_bonuses (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id  integer NOT NULL REFERENCES seasons(id) ON DELETE CASCADE,
  code       varchar NOT NULL,                        -- FB, LD, MA, MP, MD, or an admin's own
  label      varchar NOT NULL,
  award      varchar NOT NULL CHECK (award IN ('HIGHEST', 'LOWEST', 'MANUAL')),
  stat       varchar CHECK (stat IN ('PERFORMANCE_SCORE', 'KILLS', 'DEATHS', 'ASSISTS',
                            'ECON_RATING', 'FIRST_BLOODS', 'PLANTS', 'DEFUSES',
                            'HEADSHOT_PCT', 'CLUTCHES')),   -- the stat compared; empty for MANUAL
  points     smallint NOT NULL,
  position   smallint NOT NULL,
  UNIQUE (season_id, code),
  CHECK ((award = 'MANUAL') = (stat IS NULL))
);

-- Matches, games and stats -----------------------------------------------------------------

CREATE TABLE matches (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id  uuid NOT NULL REFERENCES organizations(id),
  season_id        integer NOT NULL REFERENCES seasons(id),
  match_number     smallint NOT NULL CHECK (match_number >= 1),   -- restarts at 1 in each season
  match_date       date,                              -- a future date is the "Next match" tile
  UNIQUE (season_id, match_number)
);

CREATE TABLE games (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id     integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  game_number  smallint NOT NULL CHECK (game_number >= 1),
  UNIQUE (match_id, game_number)
);

-- One player's line in one game. A stat is empty when its season didn't record it at the
-- time the game was saved.
CREATE TABLE game_stats (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id            integer NOT NULL REFERENCES games(id) ON DELETE CASCADE,
  player_id          uuid NOT NULL REFERENCES players(id),
  performance_score  integer,
  kills              smallint,
  deaths             smallint,
  assists            smallint,
  econ_rating        integer,
  first_bloods       smallint,
  plants             smallint,
  defuses            smallint,
  headshot_pct       numeric(5,2),
  clutches           smallint,
  win                boolean NOT NULL DEFAULT false,
  UNIQUE (game_id, player_id)
);
CREATE INDEX game_stats_player ON game_stats (player_id);

-- The bonuses a player won in a game.
CREATE TABLE game_stat_bonuses (
  game_stat_id  integer NOT NULL REFERENCES game_stats(id) ON DELETE CASCADE,
  bonus_id      integer NOT NULL REFERENCES season_bonuses(id) ON DELETE CASCADE,
  PRIMARY KEY (game_stat_id, bonus_id)
);
